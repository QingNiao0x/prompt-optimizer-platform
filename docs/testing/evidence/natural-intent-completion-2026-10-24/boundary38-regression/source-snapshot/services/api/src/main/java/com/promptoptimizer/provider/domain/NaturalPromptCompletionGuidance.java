package com.promptoptimizer.provider.domain;

/**
 * 自然正文实质补全的受控候选：同一指导分别关闭、开启少量内部示范，以区分两者收益。
 * 仅改变模型写作指导，复用第四版任务理解、覆盖、来源和 Plan 保护，不提供用户场景路由。
 *
 * @author QingNiao
 * @since 0.1.0
 */
public final class NaturalPromptCompletionGuidance {
    /** 仅补全指导；服务端对照与历史重放使用，未验证前不是默认策略。 */
    public static final String GUIDANCE_VERSION = "7";
    /** 相同补全指导加三份固定示范；不恢复已退役的示例参考选项。 */
    public static final String EXEMPLAR_VERSION = "8";

    /** 判断受控补全版本，不根据原文中的职业、主题或关键词切换指导。 */
    public static boolean supports(String version) {
        return GUIDANCE_VERSION.equals(version) || EXEMPLAR_VERSION.equals(version);
    }

    public static final String ENHANCE = NaturalPromptInstructions.COMMON + """
            把当前需求完善成自然、可直接交给执行者的提示词。第一句保留原定动作、对象和目标作品。
            以原始提示词、适用上下文及全部实际题答为依据，先核对目标、对象、格式、篇幅、条件和确认信息。
            已经足以执行的表达直接保留，不为显示增强而扩写、改成交付方案或增加额外作品。

            对真正影响交付的缺口，写出执行者接下来要处理的具体内容，而不只要求他“明确、完善、注意”：
            从任务对象出发，选择对这次作品最有用的内容重点、处理动作及应交付的结果，融入相应正文。
            每项补充都应使执行者少猜一个重要问题、少漏一项必要内容，或能更直接检查结果是否可用。
            用户委托设计的方法、组织和普通实现细节，转成执行者要完成的设计工作；需要推荐时说明适用条件，
            让执行者根据材料选择，不把未经用户选择的单一路线、数字、技术栈或格式设为硬性要求。
            充分需求允许不补；模糊需求可以具体重构，但不把所有可能方面都列成通用检查表。

            把已有信息用到具体行动与交付中。用户实际参数、事实和保留选择不能靠设计补造；
            真正缺失时只约束依赖它的判断或步骤，继续完成其余原定内容，不把整份作品退回补材料。
            引用和比较要求只服务本次实际判断，避免用口径、免责声明或一般正确性规则代替作品内容。
            actualAnswers 已完成的确认落实到当前执行要求，仍未知的部分保持局部未决；
            原始题答、独立对象、否定、例外、数值单位及适用条件都保留，推荐不升级为事实或确认。

            返回前对照完整输入，修正意图偏移、要求遗漏或改变、相互矛盾、空槽和重复表达。
            正文用自然段或有助于执行的少量要点，有先后依赖才列步骤；不强制模块标题和篇幅。
            mandatoryRules由平台统一组装，不在正文复写平台规则、内部记录或分类标签。
            示例需求只由本次原始提示词及实际题答决定，遵守明确禁例、事实边界和输出格式。
            framework只作组织参考，选APE/BROKE/COAST/TAG/RISE/TRACE/ERA/CARE/ROSES/ICIO/CRISPE/RACE之一，
            不因框架增加字段、任务或追问；无法可靠匹配用APE，不向用户展示框架名。
            只返回JSON：{"optimizedPrompt":"完整自然正文","framework":"参考标记","taskUnderstanding":下述记录}。
            """ + NaturalPromptInstructions.TASK_RECORD;

    /**
     * 同一候选只增加固定示范，便于独立检验示范收益；示范不进入 NaturalPromptInput 或 taskSources。
     * 示范只教补全程度及事实边界，不提供当前任务事实、用户答案或下游输出示例要求。
     */
    public static final String ENHANCE_WITH_DEMONSTRATIONS = ENHANCE + """

            <internal_rewrite_demonstrations>
            以下三例只演示怎样改写需求。它们不是本次任务或可引用来源，不复制其人物、数值、格式和措辞；
            不据此要求下游提供示例。本次仍按上述完整JSON协议返回，不返回示范的点评。

            原始需求：帮我拟个新成员入组第一周的安排。
            合适的优化提示词：请拟一份新成员入组第一周的安排，帮助他了解团队并逐步开始实际工作。
            按天安排需要了解的团队信息、上手任务和可寻求的支持，说明每天应完成什么，以及周末如何检查上手情况。
            将通用入组事项与需要团队补充的业务资料分开，让安排可以直接调整使用，不虚构团队现有制度或成员职责。
            点评：补入安排应包含的实际内容和完成标志；没有要求用户先填写岗位、制度和全部日程。

            原始需求：根据这份试运行记录写改进建议，150字以内。上周登录失败18次，本周10次，没有用户数。
            合适的优化提示词：请根据试运行记录写一段150字以内的改进建议：上周登录失败18次，本周10次，未记录用户数。
            简述失败次数的变化，再提出与登录故障直接相关的排查重点和可执行的改进动作，说明下一步应补记什么来检验效果。
            现有记录不能说明失败率或原因，相关判断留待验证，不影响交付改进建议。
            点评：已知记录用于建议，缺失分母只限制失败率判断；没有编造原因，也没有把建议改成采集方案。

            原始需求：将“Your draft is saved.”译成自然中文，只输出译文，保留句末句号。
            合适的优化提示词：将“Your draft is saved.”译成自然中文，只输出译文，保留句末句号。
            点评：需求充分，直接保留；不增加角色、解释、示例或验收段落。
            </internal_rewrite_demonstrations>
            """;

    private NaturalPromptCompletionGuidance() { }
}
