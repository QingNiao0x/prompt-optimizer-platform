import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const dir=dirname(fileURLToPath(import.meta.url));
const root=resolve(dir,'../../../../tmp/natural-completion-basis-2026-10-31/works');
const read=async path=>JSON.parse((await readFile(path,'utf8')).replace(/^\uFEFF/,''));
const fixture=(await read(resolve(dir,'holdout-open.json'))).cases.find(item=>item.id==='ABH-01');
const checked=[];

// All three generated modules were inspected before execution: pure array transformation only.
// The checker is the independently sealed pre-generation checker, never generated by the work model.
for(const arm of ['unfixed-fixture','core-repair-v3','original','31']){
  let code=fixture.context.files[0].content;
  let contractValid=true;
  if(arm!=='unfixed-fixture'){
    const response=await read(resolve(dir,'results',`ABH-01_${arm}_execute.json`));
    assert.equal(response.status,200);assert.equal(response.body.choices[0].finish_reason,'stop');
    const work=JSON.parse(response.body.choices[0].message.content);
    assert.deepEqual(Object.keys(work),['files']);assert.equal(work.files.length,1);
    assert.deepEqual(Object.keys(work.files[0]).sort(),['content','path']);
    assert.equal(work.files[0].path,'windows.mjs');assert.equal(typeof work.files[0].content,'string');
    code=work.files[0].content;
  }
  const folder=resolve(root,arm);await mkdir(folder,{recursive:true});
  await writeFile(resolve(folder,'windows.mjs'),code,{flag:'wx'});
  await writeFile(resolve(folder,'check.mjs'),fixture.acceptance.checkerSource,{flag:'wx'});
  const run=spawnSync(process.execPath,['--test','check.mjs'],{cwd:folder,encoding:'utf8',timeout:10000});
  const output=run.stdout+run.stderr;
  await writeFile(resolve(dir,`work-check-${arm}.txt`),output,{flag:'wx'});
  const count=name=>Number(output.match(new RegExp('^# '+name+' (\\d+)$','m'))?.[1]??-1);
  checked.push({arm,contractValid,exitCode:run.status,tests:count('tests'),passed:count('pass'),failed:count('fail'),
    sourceSha256:createHash('sha256').update(code).digest('hex'),sourceReviewedForExecution:true});
}
assert.equal(checked[0].failed,2,'The checker must expose the two known adjacency failures');
for(const result of checked.slice(1)){assert.equal(result.tests,10);assert.equal(result.failed,0);}
const identical=new Set(checked.slice(1).map(result=>result.sourceSha256)).size===1;
await writeFile(resolve(dir,'work-verification.json'),JSON.stringify({caseId:'ABH-01',checked,identicalDeliveredSource:identical,
  verdict:identical?'PARITY_IDENTICAL_SOURCE':'REQUIRES_COMPARATIVE_REVIEW',
  necessarySourceEditsWithinCheckedScope:0,reviewer:'Internal AI and deterministic checker; no human preference claimed',
  limits:'One already-sufficient code task, one execution per arm; no stability, cross-domain superiority, or end-to-end UI claim'},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({checked,identicalDeliveredSource:identical}));
